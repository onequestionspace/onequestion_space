const fs = require('fs');

const lines = [
  "'use client';",
  "",
  "import { useState, useRef, useEffect } from 'react';",
  "import { useQuery } from 'convex/react';",
  "import { api } from '@/convex/_generated/api';",
  "import { useAuth } from '@/hooks/useAuth';",
  "import { Bot, X, Send, Loader2, Sparkles } from 'lucide-react';",
  "",
  "interface Message {",
  "  role: 'user' | 'assistant';",
  "  content: string;",
  "}",
  "",
  "export function DashboardAI() {",
  "  const { userId } = useAuth();",
  "  const [open, setOpen] = useState(false);",
  "  const [messages, setMessages] = useState<Message[]>([]);",
  "  const [input, setInput] = useState('');",
  "  const [loading, setLoading] = useState(false);",
  "  const bottomRef = useRef<HTMLDivElement>(null);",
  "",
  "  const profile = useQuery(api.profiles.current);",
  "  const analytics = useQuery(api.analytics.getAnalytics, profile?._id ? { profileId: profile._id } : 'skip');",
  "  const questions = useQuery(api.questions.getRecentQuestions, profile?._id ? { profileId: profile._id, limit: 10 } : 'skip');",
  "  const knowledgeCount = useQuery(api.knowledge.getKnowledgeCount, userId ? { userId } : 'skip');",
  "  const subscription = useQuery(api.subscriptions.getSubscription, userId ? { userId } : 'skip');",
  "",
  "  useEffect(() => {",
  "    if (open && messages.length === 0 && profile) {",
  "      setMessages([{",
  "        role: 'assistant',",
  "        content: 'Hey ' + (profile?.displayName || 'there') + '! I know your space inside out. Ask me anything.',",
  "      }]);",
  "    }",
  "  }, [open, profile]);",
  "",
  "  useEffect(() => {",
  "    bottomRef.current?.scrollIntoView({ behavior: 'smooth' });",
  "  }, [messages]);",
  "",
  "  const buildContext = () => {",
  "    const parts: string[] = [];",
  "    if (profile) {",
  "      parts.push('PROFILE: ' + profile.displayName + ' (@' + profile.username + ')');",
  "      if (profile.bio) parts.push('Bio: ' + profile.bio);",
  "    }",
  "    if (analytics) {",
  "      parts.push('ANALYTICS: ' + analytics.totalQuestions + ' questions, ' + analytics.totalVisitors + ' visitors, ' + analytics.totalAnswers + ' answers');",
  "      const rate = analytics.totalQuestions > 0 ? Math.round((analytics.totalAnswers / analytics.totalQuestions) * 100) : 0;",
  "      parts.push('Response rate: ' + rate + '%');",
  "    }",
  "    if (subscription) {",
  "      parts.push('PLAN: ' + subscription.plan + ' — ' + subscription.messagesUsed + '/' + subscription.messagesLimit + ' credits used');",
  "    }",
  "    if (knowledgeCount) parts.push('KNOWLEDGE: ' + knowledgeCount + ' items in knowledge base');",
  "    if (questions && questions.length > 0) {",
  "      parts.push('RECENT QUESTIONS:');",
  "      questions.slice(0, 5).forEach((q: any) => parts.push('- ' + q.question));",
  "    }",
  "    return parts.join('\\n');",
  "  };",
  "",
  "  const send = async () => {",
  "    if (!input.trim() || loading) return;",
  "    const userMsg: Message = { role: 'user', content: input };",
  "    setMessages(m => [...m, userMsg]);",
  "    setInput('');",
  "    setLoading(true);",
  "    try {",
  "      const context = buildContext();",
  "      const system = 'You are a smart assistant for One Question — an AI Q&A platform. Help this user grow their audience, improve their knowledge base, and understand their analytics. Be concise and actionable.\\n\\nUSER CONTEXT:\\n' + context;",
  "      const res = await fetch('/api/dashboard-ai', {",
  "        method: 'POST',",
  "        headers: { 'Content-Type': 'application/json' },",
  "        body: JSON.stringify({ messages: [...messages, userMsg], system }),",
  "      });",
  "      const data = await res.json();",
  "      setMessages(m => [...m, { role: 'assistant', content: data.content || 'Something went wrong.' }]);",
  "    } catch {",
  "      setMessages(m => [...m, { role: 'assistant', content: 'Something went wrong. Try again.' }]);",
  "    }",
  "    setLoading(false);",
  "  };",
  "",
  "  return (",
  "    <>",
  "      <button",
  "        onClick={() => setOpen(o => !o)}",
  "        className='fixed bottom-6 right-6 z-50 w-12 h-12 rounded-full bg-gradient-to-br from-primary to-pink text-white flex items-center justify-center shadow-lg hover:scale-110 transition-all'",
  "        title='AI Assistant'",
  "      >",
  "        {open ? <X className='w-5 h-5' /> : <Bot className='w-5 h-5' />}",
  "      </button>",
  "",
  "      {open && (",
  "        <div className='fixed bottom-20 right-6 z-50 w-80 h-96 glass-card rounded-2xl border border-border flex flex-col overflow-hidden shadow-2xl'>",
  "          <div className='flex items-center gap-2 px-4 py-3 border-b border-border bg-card'>",
  "            <div className='w-6 h-6 rounded-full bg-primary/20 flex items-center justify-center'>",
  "              <Sparkles className='w-3 h-3 text-primary' />",
  "            </div>",
  "            <span className='text-sm font-semibold text-foreground'>AI Assistant</span>",
  "            <span className='text-xs text-muted-foreground ml-auto'>knows your space</span>",
  "          </div>",
  "          <div className='flex-1 overflow-y-auto p-3 space-y-3'>",
  "            {messages.map((m, i) => (",
  "              <div key={i} className={'flex ' + (m.role === 'user' ? 'justify-end' : 'justify-start')}>",
  "                <div className={'max-w-[85%] px-3 py-2 rounded-xl text-xs leading-relaxed ' + (m.role === 'user' ? 'bg-primary text-white' : 'bg-card border border-border text-foreground')}>",
  "                  {m.content}",
  "                </div>",
  "              </div>",
  "            ))}",
  "            {loading && (",
  "              <div className='flex justify-start'>",
  "                <div className='bg-card border border-border px-3 py-2 rounded-xl flex gap-1'>",
  "                  {[0,1,2].map(i => <div key={i} className='w-1.5 h-1.5 rounded-full bg-primary animate-bounce' style={{ animationDelay: i*150 + 'ms' }} />)}",
  "                </div>",
  "              </div>",
  "            )}",
  "            <div ref={bottomRef} />",
  "          </div>",
  "          <div className='flex items-center gap-2 px-3 py-2 border-t border-border'>",
  "            <input",
  "              type='text'",
  "              value={input}",
  "              onChange={e => setInput(e.target.value)}",
  "              onKeyDown={e => e.key === 'Enter' && send()}",
  "              placeholder='Ask about your space...'",
  "              className='flex-1 bg-transparent text-xs text-foreground placeholder:text-muted-foreground focus:outline-none'",
  "            />",
  "            <button onClick={send} disabled={loading || !input.trim()} className='text-primary hover:opacity-70 transition-opacity disabled:opacity-30'>",
  "              {loading ? <Loader2 className='w-3.5 h-3.5 animate-spin' /> : <Send className='w-3.5 h-3.5' />}",
  "            </button>",
  "          </div>",
  "        </div>",
  "      )}",
  "    </>",
  "  );",
  "}",
];

fs.writeFileSync('components/DashboardAI.tsx', lines.join('\n'));
console.log('DashboardAI.tsx created');
