const fs = require('fs');

// 1. Fix initialize route — get email from Clerk, handle both subscription and credits
const initRoute = [
  "import { NextRequest, NextResponse } from 'next/server';",
  "import { auth, currentUser } from '@clerk/nextjs/server';",
  "import { initializePayment } from '@/lib/paystack';",
  "",
  "export async function POST(request: NextRequest) {",
  "  try {",
  "    const { userId } = await auth();",
  "    if (!userId) return NextResponse.json({ success: false, error: 'Unauthorized' }, { status: 401 });",
  "",
  "    const user = await currentUser();",
  "    const email = user?.emailAddresses?.[0]?.emailAddress;",
  "    if (!email) return NextResponse.json({ success: false, error: 'No email found' }, { status: 400 });",
  "",
  "    const body = await request.json();",
  "    const { amount, metadata } = body;",
  "",
  "    if (!amount) return NextResponse.json({ success: false, error: 'Missing amount' }, { status: 400 });",
  "",
  "    const result = await initializePayment(email, amount, { ...metadata, userId });",
  "",
  "    return NextResponse.json({ success: true, data: result.data }, { status: 200 });",
  "  } catch (error) {",
  "    console.error('Error in /api/paystack/initialize:', error);",
  "    return NextResponse.json({ success: false, error: 'Internal server error' }, { status: 500 });",
  "  }",
  "}",
].join('\n');

fs.writeFileSync('app/api/paystack/initialize/route.ts', initRoute);
console.log('1 initialize route fixed');

// 2. Fix webhook — handle charge.success for both subscription and credits
const webhookRoute = [
  "import { NextRequest, NextResponse } from 'next/server';",
  "import { validateWebhookSignature } from '@/lib/paystack';",
  "import { ConvexHttpClient } from 'convex/browser';",
  "import { api } from '@/convex/_generated/api';",
  "",
  "const convex = new ConvexHttpClient(process.env.NEXT_PUBLIC_CONVEX_URL!);",
  "",
  "export async function POST(request: NextRequest) {",
  "  try {",
  "    const signature = request.headers.get('x-paystack-signature');",
  "    const body = await request.text();",
  "",
  "    if (!signature) return NextResponse.json({ success: false, error: 'Missing signature' }, { status: 400 });",
  "    if (!validateWebhookSignature(body, signature)) return NextResponse.json({ success: false, error: 'Invalid signature' }, { status: 401 });",
  "",
  "    const event = JSON.parse(body);",
  "",
  "    if (event.event === 'charge.success') {",
  "      const { metadata, reference, amount } = event.data;",
  "      const userId = metadata?.userId;",
  "      const type = metadata?.type;",
  "",
  "      if (!userId) {",
  "        console.error('No userId in metadata');",
  "        return NextResponse.json({ success: true }, { status: 200 });",
  "      }",
  "",
  "      if (type === 'credits') {",
  "        // Add credits to subscription",
  "        const credits = metadata?.credits || 0;",
  "        await convex.mutation(api.subscriptions.addCredits, { userId, credits });",
  "        console.log('Credits added:', credits, 'for user:', userId);",
  "      } else if (type === 'subscription') {",
  "        // Upgrade plan",
  "        const plan = metadata?.plan || 'pro';",
  "        const limits: Record<string, number> = { free: 50, pro: 500, starter: 500 };",
  "        const sub = await convex.query(api.subscriptions.getSubscription, { userId });",
  "        if (sub) {",
  "          await convex.mutation(api.subscriptions.updateSubscription, {",
  "            userId,",
  "            plan,",
  "            status: 'active',",
  "          });",
  "          // Set new message limit",
  "          await convex.mutation(api.subscriptions.addCredits, {",
  "            userId,",
  "            credits: (limits[plan] || 500) - sub.messagesLimit,",
  "          });",
  "        }",
  "        console.log('Plan upgraded to:', plan, 'for user:', userId);",
  "      }",
  "    }",
  "",
  "    return NextResponse.json({ success: true }, { status: 200 });",
  "  } catch (error) {",
  "    console.error('Webhook error:', error);",
  "    return NextResponse.json({ success: false, error: 'Internal server error' }, { status: 500 });",
  "  }",
  "}",
].join('\n');

fs.writeFileSync('app/api/paystack/webhook/route.ts', webhookRoute);
console.log('2 webhook route handles charge.success for credits + subscription');

// 3. Fix verify route
const verifyRoute = [
  "import { NextRequest, NextResponse } from 'next/server';",
  "import { verifyPayment } from '@/lib/paystack';",
  "import { auth } from '@clerk/nextjs/server';",
  "import { ConvexHttpClient } from 'convex/browser';",
  "import { api } from '@/convex/_generated/api';",
  "",
  "const convex = new ConvexHttpClient(process.env.NEXT_PUBLIC_CONVEX_URL!);",
  "",
  "export async function GET(request: NextRequest) {",
  "  try {",
  "    const { userId } = await auth();",
  "    if (!userId) return NextResponse.json({ success: false, error: 'Unauthorized' }, { status: 401 });",
  "",
  "    const { searchParams } = new URL(request.url);",
  "    const reference = searchParams.get('reference');",
  "    if (!reference) return NextResponse.json({ success: false, error: 'Missing reference' }, { status: 400 });",
  "",
  "    const result = await verifyPayment(reference);",
  "",
  "    if (result.data?.status === 'success') {",
  "      const metadata = result.data.metadata;",
  "      const type = metadata?.type;",
  "",
  "      if (type === 'credits') {",
  "        const credits = metadata?.credits || 0;",
  "        await convex.mutation(api.subscriptions.addCredits, { userId, credits });",
  "      } else if (type === 'subscription') {",
  "        const plan = metadata?.plan || 'pro';",
  "        await convex.mutation(api.subscriptions.updateSubscription, { userId, plan, status: 'active' });",
  "      }",
  "    }",
  "",
  "    return NextResponse.json({ success: true, data: result.data }, { status: 200 });",
  "  } catch (error) {",
  "    console.error('Verify error:', error);",
  "    return NextResponse.json({ success: false, error: 'Internal server error' }, { status: 500 });",
  "  }",
  "}",
].join('\n');

fs.writeFileSync('app/api/paystack/verify/route.ts', verifyRoute);
console.log('3 verify route handles post-payment redirect');
